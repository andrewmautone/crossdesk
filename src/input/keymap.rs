pub fn hid_from_win(scancode: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.1 == scancode && e.1 != NONE).map(|e| e.0)
}

pub fn win_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid && e.1 != NONE).map(|e| e.1)
}

/// macOS keycodes are reused for a few aliases (F13/Print Screen...), so the
/// mac -> HID direction prefers the dedicated entries listed below.
pub fn hid_from_mac(keycode: u16) -> Option<u16> {
    let preferred = match keycode {
        0x69 => Some(0x68), // F13
        0x6B => Some(0x69), // F14
        0x71 => Some(0x6A), // F15
        _ => None,
    };
    preferred.or_else(|| TABLE.iter().find(|e| e.2 == keycode && e.2 != NONE).map(|e| e.0))
}

pub fn mac_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid && e.2 != NONE).map(|e| e.2)
}

pub fn is_modifier(hid: u16) -> bool {
    (LCTRL..=RMETA).contains(&hid)
}

/// Swap Ctrl <-> Meta (Cmd / Win) so shortcuts keep working across operating systems.
pub fn swap_ctrl_meta(hid: u16) -> u16 {
    match hid {
        LCTRL => LMETA,
        LMETA => LCTRL,
        RCTRL => RMETA,
        RMETA => RCTRL,
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hid_values_are_unique() {
        for (i, a) in TABLE.iter().enumerate() {
            for b in &TABLE[i + 1..] {
                assert_ne!(a.0, b.0, "duplicate hid {:#x}", a.0);
                assert!(a.1 != b.1 || a.1 == NONE, "duplicate win scancode {:#x}", a.1);
            }
        }
    }

    #[test]
    fn windows_round_trip() {
        for e in TABLE {
            assert_eq!(hid_from_win(e.1), Some(e.0));
        }
    }

    #[test]
    fn mac_round_trip_for_letters() {
        assert_eq!(mac_from_hid(0x04), Some(0x00));
        assert_eq!(hid_from_mac(0x00), Some(0x04));
        assert_eq!(hid_from_mac(0x69), Some(0x68));
        assert_eq!(hid_from_mac(0x37), Some(LMETA));
    }
}
